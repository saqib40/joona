use std::time::{Duration, Instant};

use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use objc2_foundation::{NSData, NSString};

pub struct Snapshot {
    items: Vec<(String, Vec<u8>)>,
    #[allow(dead_code)]
    change_count: isize,
}

pub struct Clipboard {
    last_change_count: std::sync::atomic::AtomicIsize,
}

impl Clipboard {
    pub fn new() -> anyhow::Result<Self> {
        let count = NSPasteboard::generalPasteboard().changeCount();
        Ok(Self {
            last_change_count: std::sync::atomic::AtomicIsize::new(count),
        })
    }

    pub fn sequence() -> usize {
        NSPasteboard::generalPasteboard().changeCount() as usize
    }

    pub fn snapshot(&self) -> anyhow::Result<Snapshot> {
        let pb = NSPasteboard::generalPasteboard();
        let change_count = pb.changeCount();
        let mut items = Vec::new();

        if let Some(types) = pb.types() {
            for ty in types.iter() {
                if let Some(data) = pb.dataForType(&ty) {
                    items.push((ty.to_string(), data.to_vec()));
                }
            }
        }

        Ok(Snapshot {
            items,
            change_count,
        })
    }

    pub fn offer(&self, text: &str) -> anyhow::Result<()> {
        self.set_text(text, true)
    }

    pub fn wait_rendered(&self, _timeout: Duration) -> Option<Instant> {
        // On macOS, synthesized Cmd+V is dispatched synchronously into the active event queue.
        Some(Instant::now())
    }

    pub fn render_now(&self) -> anyhow::Result<()> {
        Ok(())
    }

    pub fn restore(&self, snapshot: Snapshot, force: bool) -> anyhow::Result<bool> {
        let pb = NSPasteboard::generalPasteboard();
        let current = pb.changeCount();
        let expected = self.last_change_count.load(std::sync::atomic::Ordering::Relaxed);

        if !force && current != expected {
            // Another application modified the clipboard while we were pasting.
            return Ok(false);
        }

        pb.clearContents();
        for (ty_name, data_bytes) in snapshot.items {
            let ty = NSString::from_str(&ty_name);
            let data = NSData::with_bytes(&data_bytes);
            pb.setData_forType(Some(&data), &ty);
        }
        self.last_change_count
            .store(pb.changeCount(), std::sync::atomic::Ordering::Relaxed);
        Ok(true)
    }

    pub fn set_text(&self, text: &str, transient: bool) -> anyhow::Result<()> {
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        let ns_str = NSString::from_str(text);
        let string_type = unsafe { NSPasteboardTypeString };
        pb.setString_forType(&ns_str, string_type);

        if transient {
            // Mark as transient/auto-generated so clipboard managers (e.g. Maccy, Paste) don't log it.
            let transient_ty = NSString::from_str("org.nspasteboard.TransientType");
            let autogen_ty = NSString::from_str("org.nspasteboard.AutoGeneratedType");
            let empty = NSData::with_bytes(&[]);
            pb.setData_forType(Some(&empty), &transient_ty);
            pb.setData_forType(Some(&empty), &autogen_ty);
        }

        self.last_change_count
            .store(pb.changeCount(), std::sync::atomic::Ordering::Relaxed);
        Ok(())
    }

    pub fn text(&self) -> anyhow::Result<Option<String>> {
        let pb = NSPasteboard::generalPasteboard();
        let string_type = unsafe { NSPasteboardTypeString };
        Ok(pb.stringForType(string_type).map(|s| s.to_string()))
    }

    pub fn copied_selection(&self) -> anyhow::Result<Option<String>> {
        self.text()
    }
}
